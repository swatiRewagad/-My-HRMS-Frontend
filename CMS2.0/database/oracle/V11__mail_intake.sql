-- ============================================================
-- CMS 2.0 — V11: cms-mail-intake schema (Oracle)
--
-- Three new tables backing the embedded SMTP receiver that accepts
-- redirected/forwarded crpc@rbi.org.in mail on cms20.rbi.org.in.
-- Pure transactional/audit storage — no reference/lookup data,
-- so this script has no seed-data section.
-- ============================================================

-- ─────────────────────────────────────────────────────────────
-- 1. INBOUND_EMAIL — one row per accepted SMTP transaction
-- ─────────────────────────────────────────────────────────────
CREATE TABLE INBOUND_EMAIL (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SMTP_MESSAGE_ID     VARCHAR2(500),
    CONTENT_SHA256      VARCHAR2(64) NOT NULL,
    ENVELOPE_FROM       VARCHAR2(320),
    ENVELOPE_TO         VARCHAR2(320) NOT NULL,
    REMOTE_IP           VARCHAR2(45) NOT NULL,
    RECEIVED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RAW_STORE_URI       VARCHAR2(500) NOT NULL,
    RAW_SIZE_BYTES      NUMBER NOT NULL,
    STATUS              VARCHAR2(20) DEFAULT 'RECEIVED' NOT NULL,
    FAILED_STAGE        VARCHAR2(20),
    QUARANTINE_REASON   VARCHAR2(30),
    ATTEMPT_COUNT       NUMBER DEFAULT 0 NOT NULL,
    NEXT_ATTEMPT_AT     TIMESTAMP,
    LAST_ERROR          VARCHAR2(2000),
    ORIGINAL_FROM       VARCHAR2(320),
    ORIGINAL_SUBJECT    VARCHAR2(1000),
    ORIGINAL_SENT_AT    TIMESTAMP,
    RESOLVED_BY         VARCHAR2(30),
    COMPLAINT_REF       VARCHAR2(100),
    LINKED_COMPLAINT_ID VARCHAR2(50),
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_INBOUND_EMAIL_SHA256 UNIQUE (CONTENT_SHA256)
);

CREATE INDEX IDX_INBOUND_EMAIL_MSGID       ON INBOUND_EMAIL (SMTP_MESSAGE_ID);
CREATE INDEX IDX_INBOUND_EMAIL_STATUS      ON INBOUND_EMAIL (STATUS);
CREATE INDEX IDX_INBOUND_EMAIL_NEXT_ATTEMPT ON INBOUND_EMAIL (STATUS, NEXT_ATTEMPT_AT);
CREATE INDEX IDX_INBOUND_EMAIL_COMPLAINT_REF ON INBOUND_EMAIL (COMPLAINT_REF);

-- ─────────────────────────────────────────────────────────────
-- 2. INBOUND_EMAIL_ATTACHMENT
-- ─────────────────────────────────────────────────────────────
CREATE TABLE INBOUND_EMAIL_ATTACHMENT (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID                NUMBER NOT NULL,
    FILENAME                VARCHAR2(500),
    DECLARED_CONTENT_TYPE   VARCHAR2(200),
    DETECTED_CONTENT_TYPE   VARCHAR2(200),
    SIZE_BYTES              NUMBER NOT NULL,
    CONTENT_SHA256          VARCHAR2(64),
    STORE_URI               VARCHAR2(500) NOT NULL,
    SCAN_STATUS             VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    EXTRACTED_TEXT_URI      VARCHAR2(500),
    CREATED_AT              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ATTACHMENT_EMAIL FOREIGN KEY (EMAIL_ID) REFERENCES INBOUND_EMAIL (ID)
);

CREATE INDEX IDX_ATTACHMENT_EMAIL_ID ON INBOUND_EMAIL_ATTACHMENT (EMAIL_ID);

-- ─────────────────────────────────────────────────────────────
-- 3. INBOUND_EMAIL_EVENT — append-only audit trail
-- ─────────────────────────────────────────────────────────────
CREATE TABLE INBOUND_EMAIL_EVENT (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID    NUMBER NOT NULL,
    EVENT_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FROM_STATUS VARCHAR2(20),
    TO_STATUS   VARCHAR2(20) NOT NULL,
    ACTOR       VARCHAR2(100) NOT NULL,
    DETAIL      VARCHAR2(2000),
    CONSTRAINT FK_EVENT_EMAIL FOREIGN KEY (EMAIL_ID) REFERENCES INBOUND_EMAIL (ID)
);

CREATE INDEX IDX_EVENT_EMAIL_ID ON INBOUND_EMAIL_EVENT (EMAIL_ID);
