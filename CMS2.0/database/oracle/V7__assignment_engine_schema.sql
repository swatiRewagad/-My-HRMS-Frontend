    VALUE_NUM_TO        NUMBER(19,4),
    VALUE_DATE_FROM     DATE,
    VALUE_DATE_TO       DATE,
    VALUE_LIST          CLOB,
    CONSTRAINT FK_ASGN_COND_RULE FOREIGN KEY (RULE_ID) REFERENCES ASGN_RULE(ID)
