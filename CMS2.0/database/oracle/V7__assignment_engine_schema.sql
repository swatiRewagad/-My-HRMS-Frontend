-- Sequences
DECLARE
    v_count NUMBER;
BEGIN
    FOR seq_rec IN (
        SELECT column_value AS seq_name FROM TABLE(SYS.ODCIVARCHAR2LIST(
            'ASGN_ATTRIBUTE_SEQ', 'ASGN_ATTRIBUTE_VALUE_SEQ',
            'ASGN_RULE_SET_SEQ', 'ASGN_RULE_SET_VERSION_SEQ',
            'ASGN_RULE_SEQ', 'ASGN_RULE_CONDITION_SEQ',
            'ASGN_RULE_OUTCOME_SEQ', 'ASGN_RULE_SET_PUB_SEQ',
            'ASGN_RR_COUNTER_SEQ', 'ASGN_DECISION_LOG_SEQ',
            'ASGN_AUDIT_EVENT_SEQ', 'ASGN_EXCLUSION_RULE_SEQ',
            'ASGN_SIM_JOB_SEQ', 'ASGN_SIM_RESULT_SEQ'
        ))
    ) LOOP
        SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = seq_rec.seq_name;
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || seq_rec.seq_name || ' START WITH 1 INCREMENT BY 1 NOCACHE';
        END IF;
    END LOOP;
END;
/

-- ─────────────────────────────────────────────────────────────
-- ASGN_ATTRIBUTE — Routing dimension registry
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_ATTRIBUTE (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID           VARCHAR2(50 CHAR) DEFAULT 'RBI-CMS' NOT NULL,
    CODE                VARCHAR2(100 CHAR) NOT NULL,
    LABEL               VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(500 CHAR),
    HELP_TEXT           VARCHAR2(1000 CHAR),
    DATA_TYPE           VARCHAR2(20 CHAR) NOT NULL,
    SOURCE_PATH         VARCHAR2(500 CHAR),
    REQUIRED            NUMBER(1) DEFAULT 0,
    VALUE_SOURCE        VARCHAR2(20 CHAR),
    LOOKUP_API_URL      VARCHAR2(500 CHAR),
    CASE_SENSITIVE      NUMBER(1) DEFAULT 0,
    INDEXABLE           NUMBER(1) DEFAULT 0,
    PII_FLAG            NUMBER(1) DEFAULT 0,
    DISPLAY_ORDER       NUMBER(10) DEFAULT 0,
    ACTIVE              NUMBER(1) DEFAULT 1,
    ALLOWED_OPERATORS   VARCHAR2(1000 CHAR),
    CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
    UPDATED_AT          TIMESTAMP(6)
);

CREATE UNIQUE INDEX UK_ASGN_ATTR_TENANT_CODE ON ASGN_ATTRIBUTE(TENANT_ID, CODE);
CREATE INDEX IDX_ASGN_ATTR_ACTIVE ON ASGN_ATTRIBUTE(TENANT_ID, ACTIVE);

-- ─────────────────────────────────────────────────────────────
-- ASGN_ATTRIBUTE_VALUE — Static allowed values
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_ATTRIBUTE_VALUE (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID           VARCHAR2(50 CHAR) DEFAULT 'RBI-CMS' NOT NULL,
    ATTRIBUTE_CODE      VARCHAR2(100 CHAR) NOT NULL,
    VALUE_CODE          VARCHAR2(100 CHAR) NOT NULL,
    VALUE_LABEL         VARCHAR2(200 CHAR) NOT NULL,
    SORT_ORDER          NUMBER(10) DEFAULT 0,
    ACTIVE              NUMBER(1) DEFAULT 1
);

CREATE INDEX IDX_ASGN_ATTRVAL_CODE ON ASGN_ATTRIBUTE_VALUE(TENANT_ID, ATTRIBUTE_CODE, ACTIVE);

-- ─────────────────────────────────────────────────────────────
-- ASGN_RULE_SET — One per decision point
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_RULE_SET (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID           VARCHAR2(50 CHAR) DEFAULT 'RBI-CMS' NOT NULL,
    DECISION_POINT      VARCHAR2(100 CHAR) NOT NULL,
    NAME                VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(1000 CHAR),
    HIT_POLICY          VARCHAR2(30 CHAR) DEFAULT 'FIRST' NOT NULL,
    ACTIVE              NUMBER(1) DEFAULT 1,
    CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
    UPDATED_AT          TIMESTAMP(6)
);

CREATE UNIQUE INDEX UK_ASGN_RS_TENANT_DP ON ASGN_RULE_SET(TENANT_ID, DECISION_POINT);

-- ─────────────────────────────────────────────────────────────
-- ASGN_RULE_SET_VERSION — Immutable versioned snapshot
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_RULE_SET_VERSION (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID           VARCHAR2(50 CHAR) DEFAULT 'RBI-CMS' NOT NULL,
    RULE_SET_ID         NUMBER(19) NOT NULL,
    VERSION_NO          NUMBER(10) NOT NULL,
    STATUS              VARCHAR2(30 CHAR) DEFAULT 'DRAFT' NOT NULL,
    EFFECTIVE_FROM      TIMESTAMP(6) WITH TIME ZONE,
    EFFECTIVE_TO        TIMESTAMP(6) WITH TIME ZONE,
    MAKER_ID            VARCHAR2(100 CHAR),
    MAKER_AT            TIMESTAMP(6),
    MAKER_REMARKS       VARCHAR2(1000 CHAR),
    CHECKER_ID          VARCHAR2(100 CHAR),
    CHECKER_AT          TIMESTAMP(6),
    CHECKER_REMARKS     VARCHAR2(1000 CHAR),
    PUBLISHED_BY        VARCHAR2(100 CHAR),
    PUBLISHED_AT        TIMESTAMP(6),
    CHECKSUM            VARCHAR2(64 CHAR),
    OPT_LOCK            NUMBER(19) DEFAULT 0,
    CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
    UPDATED_AT          TIMESTAMP(6),
    CONSTRAINT FK_ASGN_VER_RS FOREIGN KEY (RULE_SET_ID) REFERENCES ASGN_RULE_SET(ID)
);

CREATE UNIQUE INDEX UK_ASGN_VER_RS_NO ON ASGN_RULE_SET_VERSION(RULE_SET_ID, VERSION_NO);
CREATE INDEX IDX_ASGN_VER_STATUS ON ASGN_RULE_SET_VERSION(RULE_SET_ID, STATUS);

-- ─────────────────────────────────────────────────────────────
-- ASGN_RULE — One row per decision table row
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_RULE (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID           VARCHAR2(50 CHAR) DEFAULT 'RBI-CMS' NOT NULL,
    VERSION_ID          NUMBER(19) NOT NULL,
    RULE_CODE           VARCHAR2(50 CHAR) NOT NULL,
    NAME                VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(500 CHAR),
    PRIORITY            NUMBER(10) NOT NULL,
    ROW_ORDER           NUMBER(10) NOT NULL,
    ENABLED             NUMBER(1) DEFAULT 1,
    EFFECTIVE_FROM      TIMESTAMP(6) WITH TIME ZONE,
    EFFECTIVE_TO        TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
    UPDATED_AT          TIMESTAMP(6),
    CONSTRAINT FK_ASGN_RULE_VER FOREIGN KEY (VERSION_ID) REFERENCES ASGN_RULE_SET_VERSION(ID)
);

CREATE INDEX IDX_ASGN_RULE_VER ON ASGN_RULE(VERSION_ID, PRIORITY, ROW_ORDER);

-- ─────────────────────────────────────────────────────────────
-- ASGN_RULE_CONDITION — One cell in the decision table
-- ─────────────────────────────────────────────────────────────
CREATE TABLE ASGN_RULE_CONDITION (
