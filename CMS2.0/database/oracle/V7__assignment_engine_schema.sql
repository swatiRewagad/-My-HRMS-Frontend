CREATE INDEX IDX_ASGN_COND_RULE ON ASGN_RULE_CONDITION(RULE_ID);
CREATE INDEX IDX_ASGN_COND_ATTR ON ASGN_RULE_CONDITION(ATTRIBUTE_CODE);

-- ─────────────────────────────────────────────────────────────
-- ASGN_RULE_OUTCOME — Assignment target
