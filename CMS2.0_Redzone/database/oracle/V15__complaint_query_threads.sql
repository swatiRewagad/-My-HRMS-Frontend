-- ═══════════════════════════════════════════════════════════════════════════
-- Link in-thread uploads to the message that carried them (UST854). Reuses
-- COMPLAINT_ATTACHMENTS so existing size/type/virus validation applies.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_count NUMBER;

    PROCEDURE add_col(p_table VARCHAR2, p_name VARCHAR2, p_type VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = p_table AND COLUMN_NAME = p_name;
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD ' || p_name || ' ' || p_type;
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'COMPLAINT_ATTACHMENTS';
    IF v_count = 0 THEN
        RETURN;
    END IF;

    add_col('COMPLAINT_ATTACHMENTS', 'QUERY_MESSAGE_ID', 'NUMBER(19)');
    add_col('COMPLAINT_ATTACHMENTS', 'UPLOADED_BY',      'VARCHAR2(100)');
END;
/

DECLARE
    v_exists NUMBER;
    v_table  NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'COMPLAINT_ATTACHMENTS' AND COLUMN_NAME = 'QUERY_MESSAGE_ID';
    IF v_table = 0 THEN
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_exists FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_ATTACH_QUERY_MSG';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_ATTACH_QUERY_MSG ON COMPLAINT_ATTACHMENTS(QUERY_MESSAGE_ID)';
    END IF;
END;
/

-- ═══════════════════════════════════════════════════════════════════════════
-- SLA clock pause for approved extensions (UST853). The clock keeps running
-- while a request is PENDING; on approval the server pauses it and sets the new
-- deadline. SLA_PAUSE_MINUTES accumulates so a second extension does not lose
-- the first pause.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_count NUMBER;

    PROCEDURE add_col(p_table VARCHAR2, p_name VARCHAR2, p_type VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = p_table AND COLUMN_NAME = p_name;
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD ' || p_name || ' ' || p_type;
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'RE_RESPONSE_TRACKER';
    IF v_count = 0 THEN
        RETURN;
    END IF;

    add_col('RE_RESPONSE_TRACKER', 'SLA_PAUSED',        'NUMBER(1) DEFAULT 0');
    add_col('RE_RESPONSE_TRACKER', 'SLA_PAUSED_AT',     'TIMESTAMP(6)');
    add_col('RE_RESPONSE_TRACKER', 'SLA_PAUSE_MINUTES', 'NUMBER(19) DEFAULT 0');
END;
/

-- ═══════════════════════════════════════════════════════════════════════════
-- Configurable limits. No hardcoded values in code — these are read from
-- SYSTEM_CONFIG at runtime.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    PROCEDURE add_cfg(p_key VARCHAR2, p_val VARCHAR2, p_desc VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM SYSTEM_CONFIG WHERE CONFIG_KEY = p_key;
        IF v_exists = 0 THEN
            INSERT INTO SYSTEM_CONFIG (CONFIG_KEY, CONFIG_VALUE, DESCRIPTION, UPDATED_BY, UPDATED_AT)
            VALUES (p_key, p_val, p_desc, 'V15_MIGRATION', SYSTIMESTAMP);
        END IF;
    END;
BEGIN
    add_cfg('cms.query.internal_note_edit_window_minutes', '5',
            'Minutes an author may edit their own internal note before it locks (UST860)');
    add_cfg('cms.query.max_extension_days', '30',
            'Maximum extension days an RBI approver may grant on an RE response deadline (UST853)');
    add_cfg('cms.query.max_meeting_slots', '5',
            'Maximum proposed meeting slots per meeting-request query (UST855)');
    add_cfg('cms.query.max_checklist_items', '20',
            'Maximum checklist items per document-request query (UST854)');
    COMMIT;
END;
/
