-- V15: RE <-> RBI query/correspondence threads (UST853, UST854, UST855, UST856, UST857, UST860)
-- Oracle version (mirrors database/V16__complaint_query_threads.sql; the two directories' V-numbers
-- are not in sync)
--
-- Context: RE query state was three scalar columns on a per-complaint singleton row
-- (RE_RESPONSE_TRACKER.QUERY_TEXT / QUERY_RAISED_AT). RePortalService.raiseQuery did a blind
-- setQueryText(), so every new query silently OVERWROTE the previous one — the opposite of the
-- tamper-evident history UST857 requires. There was no GET for queries and no RBI-side reply
-- endpoint at all, so the RBI side could not answer an RE query except as a timeline remark
-- string, and the author was the hardcoded literal "RE_PORTAL".
--
-- RE_RESPONSE_TRACKER.QUERY_TEXT/QUERY_RAISED_AT are left in place and are now legacy-read-only.
-- EXTENSION_GRANTED/EXTENSION_DAYS were dead columns (no setter call existed anywhere in the tree)
-- and are now driven by the extension-request approval path.
--
-- Re-running is safe: every CREATE is guarded on USER_TABLES, every ALTER on USER_TAB_COLUMNS, and
-- every index on USER_INDEXES. TIMESTAMP(6) is used where MySQL uses DATETIME(6) so that messages
-- posted within the same second still order deterministically.

-- ═══════════════════════════════════════════════════════════════════════════
-- Thread header
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'COMPLAINT_QUERY';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE COMPLAINT_QUERY (
                ID                     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                COMPLAINT_ID           NUMBER(19)     NOT NULL,
                ENTITY_CODE            VARCHAR2(50)   NOT NULL,
                QUERY_TYPE             VARCHAR2(30)   NOT NULL,
                SUBJECT                VARCHAR2(500)  NOT NULL,
                DIRECTION              VARCHAR2(20)   NOT NULL,
                PENDING_WITH           VARCHAR2(10)   NOT NULL,
                STATUS                 VARCHAR2(20)   NOT NULL,
                RAISED_BY_USER_ID      VARCHAR2(100)  NOT NULL,
                RAISED_BY_NAME         VARCHAR2(200)  NOT NULL,
                RAISED_BY_ROLE         VARCHAR2(50),
                RAISED_BY_SIDE         VARCHAR2(10)   NOT NULL,
                RAISED_AT              TIMESTAMP(6)   NOT NULL,
                RESOLVED_AT            TIMESTAMP(6),
                RESOLVED_BY            VARCHAR2(100),
                PROPOSED_DEADLINE      TIMESTAMP(6),
                EXTENSION_REASON       CLOB,
                DECISION               VARCHAR2(20),
                DECIDED_BY             VARCHAR2(100),
                DECIDED_AT             TIMESTAMP(6),
                DECISION_REASON        CLOB,
                GRANTED_DEADLINE       TIMESTAMP(6),
                MEETING_PURPOSE        CLOB,
                MEETING_OUTCOME        VARCHAR2(20),
                MEETING_DECLINE_REASON CLOB,
                CREATED_AT             TIMESTAMP(6),
                UPDATED_AT             TIMESTAMP(6),
                CONSTRAINT PK_COMPLAINT_QUERY PRIMARY KEY (ID)
            )';
    END IF;
END;
/

DECLARE
    PROCEDURE add_idx(p_name VARCHAR2, p_ddl VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM USER_INDEXES WHERE INDEX_NAME = p_name;
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    add_idx('IDX_CQ_COMPLAINT', 'CREATE INDEX IDX_CQ_COMPLAINT ON COMPLAINT_QUERY(COMPLAINT_ID)');
    add_idx('IDX_CQ_PENDING',   'CREATE INDEX IDX_CQ_PENDING ON COMPLAINT_QUERY(PENDING_WITH, STATUS)');
    add_idx('IDX_CQ_ENTITY',    'CREATE INDEX IDX_CQ_ENTITY ON COMPLAINT_QUERY(ENTITY_CODE)');
    add_idx('IDX_CQ_TYPE',      'CREATE INDEX IDX_CQ_TYPE ON COMPLAINT_QUERY(QUERY_TYPE)');
END;
