-- ───────────────────────────── Indexes ─────────────────────────────
DECLARE
    PROCEDURE add_idx(p_name VARCHAR2, p_ddl VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM USER_INDEXES WHERE INDEX_NAME = p_name;
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    add_idx('IDX_REVEAL_USER',      'CREATE INDEX IDX_REVEAL_USER ON PII_REVEAL_AUDIT(USER_ID)');
    add_idx('IDX_REVEAL_COMPLAINT', 'CREATE INDEX IDX_REVEAL_COMPLAINT ON PII_REVEAL_AUDIT(COMPLAINT_NUMBER)');
    add_idx('IDX_REVEAL_AT',        'CREATE INDEX IDX_REVEAL_AT ON PII_REVEAL_AUDIT(REVEALED_AT)');
    add_idx('IDX_SECEVENT_SUBJECT', 'CREATE INDEX IDX_SECEVENT_SUBJECT ON SECURITY_EVENT(SUBJECT)');
    add_idx('IDX_SECEVENT_TYPE',    'CREATE INDEX IDX_SECEVENT_TYPE ON SECURITY_EVENT(EVENT_TYPE)');
    -- Composite: the threshold query filters subject + type + time together.
    add_idx('IDX_SECEVENT_LOOKUP',  'CREATE INDEX IDX_SECEVENT_LOOKUP ON SECURITY_EVENT(SUBJECT, EVENT_TYPE, OCCURRED_AT)');
    add_idx('IDX_ALERT_STATUS',     'CREATE INDEX IDX_ALERT_STATUS ON SECURITY_ALERT(STATUS)');
    add_idx('IDX_ALERT_SUPPRESS',   'CREATE INDEX IDX_ALERT_SUPPRESS ON SECURITY_ALERT(SUBJECT, ALERT_TYPE, RAISED_AT)');
    add_idx('IDX_REVOKE_USER',      'CREATE INDEX IDX_REVOKE_USER ON CREDENTIAL_REVOCATION(USERNAME)');
    add_idx('IDX_REVOKE_ACTIVE',    'CREATE INDEX IDX_REVOKE_ACTIVE ON CREDENTIAL_REVOCATION(ACTIVE)');
    add_idx('IDX_DELETION_AT',      'CREATE INDEX IDX_DELETION_AT ON DELETION_LOG(EXECUTED_AT)');
END;
