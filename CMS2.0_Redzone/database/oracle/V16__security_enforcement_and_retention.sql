-- ═══════════════════════════════════════════════════════════════════════════
-- V16 (Oracle) — Security enforcement, PII masking, anomaly detection, retention
--                (B1, UST873, UST875, UST877, UST890)
--
-- Oracle counterpart of database/V17__security_enforcement_and_retention.sql.
-- The V-numbers are deliberately offset by one: the MySQL and Oracle sequences
-- are tracked separately (see oracle/V15 header).
--
-- Safe to re-run: every DDL is guarded on USER_TABLES / USER_TAB_COLUMNS /
-- USER_INDEXES, and every seed on a COUNT(*) check.
-- Type mapping vs MySQL: TIMESTAMP(6) for DATETIME(6), CLOB for TEXT,
-- NUMBER(1) for TINYINT(1).
-- ═══════════════════════════════════════════════════════════════════════════

-- ───────────────────────── UST875: PII reveal audit ─────────────────────────
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'PII_REVEAL_AUDIT';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE PII_REVEAL_AUDIT (
                ID                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                USER_ID           VARCHAR2(200)  NOT NULL,
                DISPLAY_NAME      VARCHAR2(200),
                ROLES             VARCHAR2(500),
                COMPLAINT_NUMBER  VARCHAR2(50),
                FIELDS_REVEALED   VARCHAR2(1000) NOT NULL,
                CONTEXT           VARCHAR2(100),
                JUSTIFICATION     VARCHAR2(1000),
                IP_ADDRESS        VARCHAR2(50),
                REVEALED_AT       TIMESTAMP(6)   NOT NULL,
                CONSTRAINT PK_PII_REVEAL_AUDIT PRIMARY KEY (ID)
            )';
    END IF;
END;
