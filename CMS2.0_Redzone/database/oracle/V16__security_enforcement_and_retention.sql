-- ═══════════════════════════════════════════════════════════════════════════
-- Tunable thresholds — no hardcoded security values in code.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    PROCEDURE add_cfg(p_key VARCHAR2, p_val VARCHAR2, p_desc VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM SYSTEM_CONFIG WHERE CONFIG_KEY = p_key;
        IF v_exists = 0 THEN
            INSERT INTO SYSTEM_CONFIG (CONFIG_KEY, CONFIG_VALUE, DESCRIPTION, UPDATED_BY, UPDATED_AT)
            VALUES (p_key, p_val, p_desc, 'V16_MIGRATION', SYSTIMESTAMP);
        END IF;
    END;
BEGIN
    add_cfg('cms.security.pii.masking_enabled', 'true',
            'Master switch for complainant PII masking on API responses (UST875)');
    add_cfg('cms.security.pii.masked_fields',
            'complainantName,complainantPhone,complainantEmail,complainantAddress,accountNumber',
            'Comma-separated complainant fields masked by default (UST875)');
    add_cfg('cms.security.pii.reveal_roles',
            'ADMIN,CEPC_DO,CEPC_OFFICER,CEPC_INCHARGE,CEPC_SUPERVISOR,CEPC_CLOSING_AUTHORITY,RBIO_OFFICER,RBIO_SUPERVISOR,RBIO_CONCILIATOR,RBIO_ADJUDICATOR',
            'Roles permitted to request an audited PII reveal; RE roles excluded by design (UST875)');
    add_cfg('cms.security.pii.require_justification', 'true',
            'Require a typed reason before revealing complainant PII (UST875)');
    add_cfg('cms.security.pii.min_justification_length', '10',
            'Minimum characters in a PII reveal justification (UST875)');

    add_cfg('cms.security.anomaly.enabled', 'true',
            'Master switch for suspicious-access detection (UST873)');
    add_cfg('cms.security.anomaly.window_minutes', '10',
            'Sliding window in minutes over which security events are counted (UST873)');
    add_cfg('cms.security.anomaly.denied_access_threshold', '10',
            'Denied-access events by one subject in the window before an alert is raised (UST873)');
    add_cfg('cms.security.anomaly.cross_entity_threshold', '3',
            'Cross-entity access attempts before an alert; lower because it implies probing (UST873)');
    add_cfg('cms.security.anomaly.pii_reveal_threshold', '25',
            'Authorised PII reveals by one user in the window before it looks like harvesting (UST873)');
    add_cfg('cms.security.anomaly.distinct_entity_threshold', '3',
            'Distinct entities touched in the window before enumeration is suspected (UST873)');
    add_cfg('cms.security.anomaly.alert_suppression_minutes', '60',
            'Minutes before the same subject/type raises another alert (UST873)');

    add_cfg('cms.security.retention.enabled', 'true',
            'Whether the nightly retention sweep evaluates policies (UST890)');
    -- Deliberately false: dry run until an operator turns destruction on.
    add_cfg('cms.security.retention.destructive_enabled', 'false',
            'When false the retention sweep is a dry run and deletes nothing (UST890)');
    add_cfg('cms.security.retention.batch_limit', '5000',
            'Maximum rows one retention run may affect per policy (UST890)');
    COMMIT;
END;
