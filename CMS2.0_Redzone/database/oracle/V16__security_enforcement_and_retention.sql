-- ═══════════════════════════════════════════════════════════════════════════
-- Retention policies. Audit categories get 7 years (2555 days) independently of
-- the operational data they describe.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    PROCEDURE add_policy(p_category VARCHAR2, p_table VARCHAR2, p_ts_col VARCHAR2,
                         p_days NUMBER, p_audit NUMBER, p_redact NUMBER,
                         p_redact_cols VARCHAR2, p_enabled NUMBER, p_desc VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM RETENTION_POLICY WHERE CATEGORY = p_category;
        IF v_exists = 0 THEN
            INSERT INTO RETENTION_POLICY (CATEGORY, TARGET_TABLE, TIMESTAMP_COLUMN, RETENTION_DAYS,
                                          AUDIT_CATEGORY, REDACT_INSTEAD_OF_DELETE, REDACT_COLUMNS,
                                          ENABLED, DESCRIPTION, UPDATED_BY, UPDATED_AT)
            VALUES (p_category, p_table, p_ts_col, p_days, p_audit, p_redact, p_redact_cols,
                    p_enabled, p_desc, 'V16_MIGRATION', SYSTIMESTAMP);
        END IF;
    END;
BEGIN
    add_policy('AUDIT_LOG', 'AUDIT_LOG', 'TIMESTAMP', 2555, 1, 0, NULL, 1,
               'Workflow audit trail — 7 year statutory retention, independent of complaint retention');
    add_policy('PII_REVEAL_AUDIT', 'PII_REVEAL_AUDIT', 'REVEALED_AT', 2555, 1, 0, NULL, 1,
               'PII reveal trail — 7 year retention');
    add_policy('CONFIG_AUDIT_LOG', 'CONFIG_AUDIT_LOG', 'CHANGED_AT', 2555, 1, 0, NULL, 1,
               'Configuration change trail — 7 year retention');
    add_policy('SECURITY_EVENT', 'SECURITY_EVENT', 'OCCURRED_AT', 730, 1, 0, NULL, 1,
               'Raw security events — 2 years; the derived alerts are kept longer');
    add_policy('SECURITY_ALERT', 'SECURITY_ALERT', 'RAISED_AT', 2555, 1, 0, NULL, 1,
               'Security alerts — 7 year retention');
    add_policy('IN_APP_NOTIFICATION', 'IN_APP_NOTIFICATIONS', 'CREATED_AT', 365, 0, 0, NULL, 1,
               'In-app notifications — 1 year, transient operational data');
    -- Redacts rather than deletes: deleting a closed complaint would orphan its
    -- history, attachments and query threads. Disabled pending sign-off.
    add_policy('COMPLAINT_PII', 'COMPLAINTS', 'CLOSED_AT', 2555, 0, 1,
               'COMPLAINANT_NAME,COMPLAINANT_EMAIL,COMPLAINANT_PHONE,COMPLAINANT_ADDRESS,ACCOUNT_NUMBER',
               0,
               'Redacts complainant PII on complaints closed over 7 years ago, preserving the record shell. Disabled pending sign-off.');
    COMMIT;
END;
/

