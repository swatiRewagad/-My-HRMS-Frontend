-- ═══════════════════════════════════════════════════════════════════════════
-- 7. Configurable thresholds. No hardcoded values in code — all read via SystemConfigService.
--    Prefixed cms.reassign.* so they cannot collide with another session's keys.
--
--    The excluded-status list for the UST838 workload count lives in SYSTEM_CONFIG rather than
--    Java because this codebase already contains FOUR disagreeing hardcoded CLOSED_STATUSES lists
--    (WorkflowController:57, NotificationScheduledTasks:29, AppealWorkflowService:36,
--    AppealController:28); a fifth would guarantee the workload figure drifts from what the rest
--    of the system considers closed, with no way to correct it without a redeploy.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    PROCEDURE add_cfg(p_key VARCHAR2, p_val VARCHAR2, p_desc VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM SYSTEM_CONFIG WHERE CONFIG_KEY = p_key;
        IF v_exists = 0 THEN
            INSERT INTO SYSTEM_CONFIG (CONFIG_KEY, CONFIG_VALUE, DESCRIPTION, UPDATED_BY, UPDATED_AT)
            VALUES (p_key, p_val, p_desc, 'V28_MIGRATION', SYSTIMESTAMP);
        END IF;
    END;
BEGIN
    add_cfg('cms.reassign.workload.excluded_statuses',
            'DRAFT,CLOSED,RESOLVED,REJECTED,WITHDRAWN,ADJUDICATED,CONCILIATED,ORDER_PASSED,NON_MAINTAINABLE',
            'Record statuses excluded from the RE nodal officer workload count — drafts and closed work (UST838)');
    add_cfg('cms.reassign.bulk.max_records', '50',
