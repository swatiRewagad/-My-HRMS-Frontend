-- ═══════════════════════════════════════════════════════════════════════════
-- V28 (Oracle) — RE nodal officer reassignment
--                (UST838, UST839, UST840, UST841, UST842, UST843, UST844, UST845)
--
-- Oracle counterpart of database/V29__re_nodal_reassignment.sql. The V-numbers are
-- deliberately offset by one: the MySQL and Oracle sequences are tracked separately
-- (see oracle/V15 and oracle/V16 headers).
--
-- Context: this cluster was entirely unbuilt. The only "bulk reassign" in the codebase was
-- CrpcHeadController.bulkReassign, a stub that returned {"status":"reassigned"} and persisted
-- nothing, and it was officer-side rather than RE-side in any case.
--
-- Six things this migration establishes:
--
--   1. NODAL_OFFICER_RECORDS. Unlike the MySQL twin, on Oracle this table is NOT new — it is
--      already defined unguarded in oracle/V5__complete_ddl_dml.sql:906, which is where the
--      canonical column set lives. The CREATE below is therefore guarded on USER_TABLES and
--      reproduces V5 exactly, so it only fires on a schema built without V5 (and is a no-op on
--      every existing database). The MySQL side is the mirror case: there the table had no written
--      definition at all and was created implicitly by Hibernate ddl-auto, so dev and prod schemas
--      had no shared source of truth. Both files now say the same thing.
--
--   2. VERSION on NODAL_OFFICER_RECORDS — the optimistic lock for UST839, and the first @Version
--      column in cms-backend. NULL on existing rows is intentional: Hibernate treats a null version
--      as unversioned and seeds it on first write, so there is no backfill and legacy writers keep
--      working. A DEFAULT would not help, because the rows already exist.
--
--   3. ENTITY_CODE on NODAL_OFFICER_RECORDS. The table previously identified an entity only by the
--      free-text ENTITY_NAME, but RequestIdentity supplies an entity *code*, so server-side
--      authorisation was not possible: two similarly-named entities could not be told apart. Left
--      NULL for historical rows, and the service refuses a record whose code is null rather than
--      assuming it belongs to the caller.
--
--   4. ENTITY_USERS — the candidate directory (UST841). Sourced from the database rather than
--      Keycloak because the `cms` realm contains no RE_* users and no RE_* roles at all, so
--      enumerating the identity provider returns nothing. RE_ROLE is a column, not a hardcoded Java
--      list, because the NO-vs-Contact-Person distinction is master data. NOTE: seeding real RE users
--      into the realm remains a prerequisite for actual SSO; this table is the source of record for
--      who exists, not a substitute for authentication.
--
--   5. REASSIGNMENT_REQUESTS / _CLARIFICATIONS / REASSIGNMENT_HISTORY. The reason column is
--      immutable at the JPA layer (updatable = false) per UST840; clarifications are separate
--      append-only rows. History is a separate table from requests because a report must count
--      movements that actually happened, not intents — counting requests would include rejections.
--      History is deliberately NOT written to COMPLAINT_TIMELINE: an entity-internal staffing change
--      is not part of the complaint narrative shared beyond the entity.
--
--   6. NOTIFICATION_DELIVERY_LOG — one append-only row per delivery attempt (UST845). A separate
--      table rather than columns on IN_APP_NOTIFICATIONS, because delivery is one-to-many (multiple
--      attempts, multiple channels) and would not fit on the notification row without discarding
--      earlier attempts.
--
-- Re-running is safe: every CREATE TABLE is guarded on USER_TABLES, every ADD COLUMN on
-- USER_TAB_COLUMNS, every CREATE INDEX on USER_INDEXES, and every seed on a COUNT(*). Guards
-- tolerate a table an earlier baseline (V5) or Hibernate already created.
--
-- Type mapping vs MySQL (as documented in oracle/V16): DATETIME(6) -> TIMESTAMP(6), TEXT -> CLOB,
-- TINYINT(1) -> NUMBER(1), BIGINT -> NUMBER(19), INT -> NUMBER(10), VARCHAR(n) -> VARCHAR2(n).
-- AUTO_INCREMENT primary keys become GENERATED BY DEFAULT AS IDENTITY, which needs no sequence
-- and therefore no sequence guard.
-- ═══════════════════════════════════════════════════════════════════════════

-- ═══════════════════════════════════════════════════════════════════════════
-- 1. NODAL_OFFICER_RECORDS — guarded, column-for-column identical to
--    oracle/V5__complete_ddl_dml.sql:906. Present here only so a schema bootstrapped from a
--    partial baseline still gets the table the reassignment code depends on; on any database
--    that ran V5 the guard skips it and the existing table is left exactly as it is.
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'NODAL_OFFICER_RECORDS';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE NODAL_OFFICER_RECORDS (
                ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                COMPLAINT_NUMBER    VARCHAR2(50) NOT NULL,
                ENTITY_NAME         VARCHAR2(200),
                NODAL_OFFICER_NAME  VARCHAR2(200),
                PNO_NAME            VARCHAR2(200),
                DESIGNATION         VARCHAR2(100),
                EMAIL               VARCHAR2(200),
                PHONE               VARCHAR2(20),
                STATUS              VARCHAR2(30) DEFAULT ''INFORMATION_REQUIRED'' NOT NULL,
                ASSIGNED_TO         VARCHAR2(200),
                CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
                LAST_MODIFIED_AT    TIMESTAMP(6) DEFAULT SYSTIMESTAMP
            )';
    END IF;
END;
/

-- ═══════════════════════════════════════════════════════════════════════════
-- 2 + 3. VERSION and ENTITY_CODE on NODAL_OFFICER_RECORDS
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_count NUMBER;

    PROCEDURE add_col(p_table VARCHAR2, p_name VARCHAR2, p_type VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = p_table AND COLUMN_NAME = p_name;
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD ' || p_name || ' ' || p_type;
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'NODAL_OFFICER_RECORDS';
    IF v_count > 0 THEN
        -- Nullable with no DEFAULT, not 0: Hibernate seeds a null version on first write, so
        -- existing rows need no backfill and writers that predate optimistic locking are
        -- unaffected. A DEFAULT would not help either way, because the rows already exist.
        add_col('NODAL_OFFICER_RECORDS', 'VERSION',     'NUMBER(19)');
        -- Nullable for the same reason, but with a different consequence: a record whose code is
        -- unknown is refused by the service rather than assumed to belong to the caller.
        add_col('NODAL_OFFICER_RECORDS', 'ENTITY_CODE', 'VARCHAR2(50)');
    END IF;
END;
/

