            'CREATE INDEX IDX_NO_ENTITY ON NODAL_OFFICER_RECORDS(ENTITY_NAME)');
    add_idx('IDX_NO_STATUS',
            'CREATE INDEX IDX_NO_STATUS ON NODAL_OFFICER_RECORDS(STATUS)');
    add_idx('IDX_NO_LAST_MODIFIED',
            'CREATE INDEX IDX_NO_LAST_MODIFIED ON NODAL_OFFICER_RECORDS(LAST_MODIFIED_AT)');
    add_idx('IDX_NO_ENTITY_CODE_ASSIGNED',
            'CREATE INDEX IDX_NO_ENTITY_CODE_ASSIGNED ON NODAL_OFFICER_RECORDS(ENTITY_CODE, ASSIGNED_TO)');
    add_idx('IDX_NO_ENTITY_CODE_STATUS',
            'CREATE INDEX IDX_NO_ENTITY_CODE_STATUS ON NODAL_OFFICER_RECORDS(ENTITY_CODE, STATUS)');
