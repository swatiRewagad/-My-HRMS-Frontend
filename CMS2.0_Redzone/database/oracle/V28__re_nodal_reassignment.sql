-- Backfill ENTITY_CODE from REGULATED_ENTITIES where the free-text name matches exactly.
-- Deliberately exact (after trimming and lowercasing), not fuzzy: a near-match that guessed wrong
-- would attach a record to the wrong bank and make it visible to an entity that should never see
-- it. Rows that do not match are left NULL and stay invisible to entity-scoped callers, which is
-- the safe direction.
--
-- Two Oracle-specific points:
--   * MySQL's `UPDATE t JOIN u ... SET` has no Oracle equivalent, so this is written as a
--     correlated scalar subquery with a matching EXISTS. The EXISTS is not redundant: without it,
--     a non-matching row would be set to NULL by the subquery returning no row, and although that
--     is the value it already holds, the statement would needlessly rewrite every unmatched row.
--     ROWNUM = 1 is deliberately NOT added to the subquery: if two REGULATED_ENTITIES rows share a
--     name, this raises ORA-01427 and the migration stops, rather than silently picking one of them
--     and attaching the record to a bank nobody chose. That is the same refusal-to-guess the exact
--     match above exists for. MySQL's JOIN form would have picked one arbitrarily, so on Oracle
--     this case is caught rather than absorbed.
--   * REGULATED_ENTITIES on the Oracle baseline (oracle/V1:65, V5:99) has NAME and no ENTITY_CODE
--     column at all, whereas the MySQL schema this backfill was written against has ENTITY_NAME
--     and ENTITY_CODE. The whole block is therefore guarded on those two columns existing, not
--     merely on the table existing, so on a stock Oracle schema this is a clean no-op instead of
--     an ORA-00904. Once REGULATED_ENTITIES gains ENTITY_CODE / ENTITY_NAME the backfill starts
--     working with no change here.
DECLARE
    v_table NUMBER;
    v_code  NUMBER;
    v_name  NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table FROM USER_TABLES WHERE TABLE_NAME = 'REGULATED_ENTITIES';

    SELECT COUNT(*) INTO v_code FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'REGULATED_ENTITIES' AND COLUMN_NAME = 'ENTITY_CODE';

    SELECT COUNT(*) INTO v_name FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'REGULATED_ENTITIES' AND COLUMN_NAME = 'ENTITY_NAME';

    IF v_table > 0 AND v_code > 0 AND v_name > 0 THEN
        EXECUTE IMMEDIATE '
            UPDATE NODAL_OFFICER_RECORDS n
               SET n.ENTITY_CODE = (SELECT re.ENTITY_CODE
                                      FROM REGULATED_ENTITIES re
                                     WHERE TRIM(LOWER(re.ENTITY_NAME)) = TRIM(LOWER(n.ENTITY_NAME)))
             WHERE n.ENTITY_CODE IS NULL
               AND n.ENTITY_NAME IS NOT NULL
               AND EXISTS (SELECT 1
                             FROM REGULATED_ENTITIES re
                            WHERE TRIM(LOWER(re.ENTITY_NAME)) = TRIM(LOWER(n.ENTITY_NAME)))';
        COMMIT;
    END IF;
END;
/

