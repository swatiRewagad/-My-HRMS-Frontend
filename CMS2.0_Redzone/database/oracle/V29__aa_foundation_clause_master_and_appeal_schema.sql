-- V29: AA foundation — Closure Clause Master, Appeal schema expansion, REOPENED support
-- Oracle version — twin of MySQL V31. Oracle numbering runs behind MySQL by convention; the two
-- directories are not in step and each takes its own next free number.
--
-- Context: the Appellate Authority module could not implement its own user stories.
--
--   1. CLOSURE_CLAUSE_MASTER is new. The closure-clause vocabulary was a hardcoded List<Map> inside
--      WorkflowController.getClosureClauses, so a Scheme amendment required a code release — and the
--      appeal path never read it anyway. Classification (APPEAL vs REPRESENTATION) was taken from a
--      request parameter defaulting to 'APPEAL', which meant the browser decided a citizen's
--      statutory recourse.
--
--      Appealability is PARTY-DEPENDENT, hence two flag columns rather than one. Per the RBI ruling:
--      a complainant may appeal a closure under 15(1)(a) or 15(1)(b); a regulated entity may appeal
--      only under 15(1)(b). Everything else is a representation. This SUPERSEDES the old hardcoded
--      list, which also marked 16(2)(c)-(f) 'appellable' — a flag no code ever read.
--
--      Only RBIOS_2021 is seeded. RBIOS 2026 clause numbers are deliberately NOT invented: they are
--      pending RBI confirmation, and a guessed clause number in a citizen-facing closure letter is a
--      legal defect. The table is scheme-versioned and date-bounded so 2026 arrives as data, and a
--      complaint is always judged under the Scheme in force when it was created.
--
--   2. APPEALS gains the Register-milestone intake fields, provenance (CREATED_BY, ROUTED_BY,
--      PUT_UP_TO) and entity linkage. Without CREATED_BY the 'Created By Me' view is impossible;
--      without ROUTED_BY_USER_ID every 'send back to the ORIGINAL officer' story is unimplementable,
--      because send-back currently round-robins to a random holder of the role.
--
--   3. APPEAL_TIMELINE gains FIELD_NAME/OLD_VALUE/NEW_VALUE so a classification override records what
--      actually changed. The timeline could only say 'status went X to Y'.
--
--   4. APPEAL_ATTACHMENTS is new. Appeal documents were written as COMPLAINT_ATTACHMENTS rows with
--      the appeal number in the complaint-number column.
--
--   5. COMPLAINTS.REOPENED_AT plus an index on WORKFLOW_STAGE. 'Closed or reopened' could not be
--      expressed as a status filter: reopen is recorded only as WORKFLOW_STAGE='REOPENED'.
--
-- Re-running is safe: every DDL is guarded on USER_TABLES / USER_TAB_COLUMNS / USER_INDEXES and
-- every seed on a COUNT(*).

-- ═══════════════════════════════════════════════════════════════════════════
-- 1. CLOSURE_CLAUSE_MASTER
-- ═══════════════════════════════════════════════════════════════════════════
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'CLOSURE_CLAUSE_MASTER';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE CLOSURE_CLAUSE_MASTER (
                ID                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                SCHEME_VERSION            VARCHAR2(20)  NOT NULL,
                CLAUSE_CODE               VARCHAR2(40)  NOT NULL,
                LABEL                     VARCHAR2(300) NOT NULL,
                LABEL_KEY                 VARCHAR2(160),
                CATEGORY                  VARCHAR2(40)  NOT NULL,
                APPEALABLE_BY_COMPLAINANT NUMBER(1)     DEFAULT 0 NOT NULL,
                APPEALABLE_BY_ENTITY      NUMBER(1)     DEFAULT 0 NOT NULL,
                RESTRICTED_TO_ROLES       VARCHAR2(300),
                EFFECTIVE_FROM            DATE,
                EFFECTIVE_TO              DATE,
                ACTIVE                    NUMBER(1)     DEFAULT 1 NOT NULL,
                CREATED_AT                TIMESTAMP(6),
                UPDATED_AT                TIMESTAMP(6),
                CONSTRAINT PK_CLOSURE_CLAUSE_MASTER PRIMARY KEY (ID),
                -- One row per clause per scheme version: a duplicate would make a legal
                -- determination ambiguous, which must be impossible rather than merely unlikely.
                CONSTRAINT UK_CCM_SCHEME_CLAUSE UNIQUE (SCHEME_VERSION, CLAUSE_CODE)
            )';
    END IF;
END;
/

