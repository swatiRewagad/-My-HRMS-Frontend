-- RBIOS 2021 clauses. Seeded here as well as in ClosureClauseMasterSeeder so a database restored
-- without an application boot still classifies correctly.
DECLARE
    TYPE t_clause IS RECORD (
        code       VARCHAR2(40),
        label      VARCHAR2(300),
        label_key  VARCHAR2(160),
        category   VARCHAR2(40),
        by_compl   NUMBER,
        by_entity  NUMBER,
        roles      VARCHAR2(300)
    );
    TYPE t_clauses IS TABLE OF t_clause;
    v_rows   t_clauses;
    v_exists NUMBER;
    v_scheme CONSTANT VARCHAR2(20) := 'RBIOS_2021';
    v_omb    CONSTANT VARCHAR2(300) := 'OMBUDSMAN,RBIO_ADMIN,ADMIN';
BEGIN
    v_rows := t_clauses(
        t_clause('15(1)(a)', 'Award - full relief granted',                         'clause.15_1_a', 'AWARD',            1, 0, v_omb),
        t_clause('15(1)(b)', 'Award - partial relief with compensation',            'clause.15_1_b', 'AWARD',            1, 1, v_omb),
        t_clause('16(1)',    'Resolved to the satisfaction of the complainant',     'clause.16_1',   'RESOLUTION',       0, 0, NULL),
        t_clause('16(2)(a)', 'Not maintainable - time barred',                      'clause.16_2_a', 'NON_MAINTAINABLE', 0, 0, NULL),
        t_clause('16(2)(b)', 'Not maintainable - frivolous or vexatious',           'clause.16_2_b', 'NON_MAINTAINABLE', 0, 0, NULL),
        t_clause('16(2)(c)', 'Not maintainable - sub-judice',                       'clause.16_2_c', 'NON_MAINTAINABLE', 0, 0, v_omb),
        t_clause('16(2)(d)', 'Not maintainable - outside jurisdiction',             'clause.16_2_d', 'NON_MAINTAINABLE', 0, 0, v_omb),
        t_clause('16(2)(e)', 'Not maintainable - already settled by RBI',           'clause.16_2_e', 'NON_MAINTAINABLE', 0, 0, v_omb),
        t_clause('16(2)(f)', 'Not maintainable - covered by another dispute mechanism', 'clause.16_2_f', 'NON_MAINTAINABLE', 0, 0, v_omb),
        t_clause('16(2)(g)', 'Not maintainable - anonymous complaint',              'clause.16_2_g', 'NON_MAINTAINABLE', 0, 0, NULL),
        t_clause('16(2)(h)', 'Not maintainable - insufficient information',         'clause.16_2_h', 'NON_MAINTAINABLE', 0, 0, NULL),
        t_clause('16(3)',    'Closed - complainant not responding',                 'clause.16_3',   'CLOSURE',          0, 0, NULL),
        t_clause('16(4)',    'Closed - matter settled between the parties',         'clause.16_4',   'CLOSURE',          0, 0, NULL)
    );

    FOR i IN 1 .. v_rows.COUNT LOOP
        SELECT COUNT(*) INTO v_exists FROM CLOSURE_CLAUSE_MASTER
         WHERE SCHEME_VERSION = v_scheme AND CLAUSE_CODE = v_rows(i).code;
        IF v_exists = 0 THEN
            INSERT INTO CLOSURE_CLAUSE_MASTER
                (SCHEME_VERSION, CLAUSE_CODE, LABEL, LABEL_KEY, CATEGORY,
                 APPEALABLE_BY_COMPLAINANT, APPEALABLE_BY_ENTITY, RESTRICTED_TO_ROLES,
                 ACTIVE, CREATED_AT, UPDATED_AT)
            VALUES (v_scheme, v_rows(i).code, v_rows(i).label, v_rows(i).label_key, v_rows(i).category,
                    v_rows(i).by_compl, v_rows(i).by_entity, v_rows(i).roles,
                    1, SYSTIMESTAMP, SYSTIMESTAMP);
        END IF;
    END LOOP;
    COMMIT;
END;
/

-- Corrective UPDATEs, scoped BY CLAUSE CODE. The seeder is insert-if-absent, so a database seeded
-- before the party-dependent ruling would still carry a single-flag interpretation.
UPDATE CLOSURE_CLAUSE_MASTER
   SET APPEALABLE_BY_COMPLAINANT = 1, APPEALABLE_BY_ENTITY = 0, UPDATED_AT = SYSTIMESTAMP
 WHERE SCHEME_VERSION = 'RBIOS_2021' AND CLAUSE_CODE = '15(1)(a)'
   AND (APPEALABLE_BY_COMPLAINANT <> 1 OR APPEALABLE_BY_ENTITY <> 0);

UPDATE CLOSURE_CLAUSE_MASTER
   SET APPEALABLE_BY_COMPLAINANT = 1, APPEALABLE_BY_ENTITY = 1, UPDATED_AT = SYSTIMESTAMP
 WHERE SCHEME_VERSION = 'RBIOS_2021' AND CLAUSE_CODE = '15(1)(b)'
   AND (APPEALABLE_BY_COMPLAINANT <> 1 OR APPEALABLE_BY_ENTITY <> 1);

UPDATE CLOSURE_CLAUSE_MASTER
   SET APPEALABLE_BY_COMPLAINANT = 0, APPEALABLE_BY_ENTITY = 0, UPDATED_AT = SYSTIMESTAMP
 WHERE SCHEME_VERSION = 'RBIOS_2021'
   AND CLAUSE_CODE NOT IN ('15(1)(a)', '15(1)(b)')
   AND (APPEALABLE_BY_COMPLAINANT <> 0 OR APPEALABLE_BY_ENTITY <> 0);
COMMIT;

