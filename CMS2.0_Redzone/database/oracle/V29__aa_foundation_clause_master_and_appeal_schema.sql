-- Backfill from the CEPC/RBIO reopen path so existing reopened complaints are findable.
DECLARE
    v_col NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_col FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'COMPLAINTS' AND COLUMN_NAME = 'LAST_REOPENED_AT';
    IF v_col > 0 THEN
        EXECUTE IMMEDIATE 'UPDATE COMPLAINTS SET REOPENED_AT = LAST_REOPENED_AT
                            WHERE REOPENED_AT IS NULL AND LAST_REOPENED_AT IS NOT NULL';
        COMMIT;
    END IF;
END;
