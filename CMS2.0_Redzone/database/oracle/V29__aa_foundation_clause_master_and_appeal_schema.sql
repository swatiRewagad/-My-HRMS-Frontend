DECLARE
    PROCEDURE add_col(p_table VARCHAR2, p_name VARCHAR2, p_type VARCHAR2) IS
        v_tab NUMBER;
        v_col NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_tab FROM USER_TABLES WHERE TABLE_NAME = p_table;
        IF v_tab = 0 THEN
            RETURN;
        END IF;
        SELECT COUNT(*) INTO v_col FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = p_table AND COLUMN_NAME = p_name;
        IF v_col = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD ' || p_name || ' ' || p_type;
        END IF;
    END;
BEGIN
    -- Classification override audit
    add_col('APPEALS', 'CLASSIFICATION_OVERRIDDEN',      'NUMBER(1) DEFAULT 0');
    add_col('APPEALS', 'CLASSIFICATION_OVERRIDE_REASON', 'VARCHAR2(1000)');
    add_col('APPEALS', 'CLASSIFICATION_OVERRIDDEN_BY',   'VARCHAR2(200)');
    add_col('APPEALS', 'CLASSIFICATION_OVERRIDDEN_AT',   'TIMESTAMP(6)');

    add_col('APPEALS', 'CLOSURE_CLAUSE',                 'VARCHAR2(40)');

    -- Provenance. NULL on historical rows: they genuinely have no recorded creator, and inventing
    -- one would be worse than an honest blank in the 'Created By Me' view.
    add_col('APPEALS', 'CREATED_BY',                     'VARCHAR2(200)');
    add_col('APPEALS', 'CREATED_BY_ROLE',                'VARCHAR2(50)');
    add_col('APPEALS', 'ROUTED_BY_USER_ID',              'VARCHAR2(200)');
    add_col('APPEALS', 'ROUTED_BY_ROLE',                 'VARCHAR2(50)');
    add_col('APPEALS', 'PUT_UP_TO_USER_ID',              'VARCHAR2(200)');

    -- Entity linkage
    add_col('APPEALS', 'ENTITY_CODE',                    'VARCHAR2(100)');
    add_col('APPEALS', 'RESOLVED_PNO_USER_ID',           'VARCHAR2(200)');

    -- Register-milestone intake
    add_col('APPEALS', 'APPEAL_FILED_BY',                'VARCHAR2(30)');
    add_col('APPEALS', 'SOURCE_OF_APPEAL',               'VARCHAR2(60)');
    add_col('APPEALS', 'MODE_OF_RECEIPT',                'VARCHAR2(30)');
    add_col('APPEALS', 'APPELLANT_ADDRESS1',             'VARCHAR2(300)');
    add_col('APPEALS', 'APPELLANT_ADDRESS2',             'VARCHAR2(300)');
    add_col('APPEALS', 'APPELLANT_CITY',                 'VARCHAR2(100)');
    add_col('APPEALS', 'APPELLANT_DISTRICT',             'VARCHAR2(100)');
    add_col('APPEALS', 'APPELLANT_STATE',                'VARCHAR2(100)');
    add_col('APPEALS', 'APPELLANT_COUNTRY',              'VARCHAR2(100)');
    add_col('APPEALS', 'APPELLANT_PINCODE',              'VARCHAR2(10)');
    add_col('APPEALS', 'CATEGORY_ID',                    'NUMBER(19)');
    add_col('APPEALS', 'ENTITY_NAME',                    'VARCHAR2(300)');
    add_col('APPEALS', 'ENTITY_REGION',                  'VARCHAR2(100)');
    add_col('APPEALS', 'ENTITY_CATEGORY',                'VARCHAR2(100)');
    add_col('APPEALS', 'ENTITY_BRANCH',                  'VARCHAR2(200)');
    add_col('APPEALS', 'BSR_IFSC_CODE',                  'VARCHAR2(40)');
    add_col('APPEALS', 'ACCOUNT_NUMBER',                 'VARCHAR2(60)');
    add_col('APPEALS', 'CARD_NUMBER',                    'VARCHAR2(60)');
    add_col('APPEALS', 'NODAL_OFFICER_NAME',             'VARCHAR2(200)');
    -- Nullable, not DEFAULT 0: 'not yet answered' and 'answered No' are different, and the Register
    -- milestone must be able to block on an unanswered mandatory checkbox.
    add_col('APPEALS', 'IS_COMPLAINANT_ADVOCATE',        'NUMBER(1)');
    add_col('APPEALS', 'HAS_RELATED_COURT_TRIAL',        'NUMBER(1)');

    -- Regulated-entity sign-off for PNO-created appeals
    add_col('APPEALS', 'ED_APPROVAL_GIVEN',              'NUMBER(1)');
    add_col('APPEALS', 'ED_APPROVAL_DATE',               'TIMESTAMP(6)');
    add_col('APPEALS', 'ED_APPROVAL_COMMENTS',           'VARCHAR2(2000)');

    -- Field-level audit on the timeline
    add_col('APPEAL_TIMELINE', 'FIELD_NAME',             'VARCHAR2(60)');
    add_col('APPEAL_TIMELINE', 'OLD_VALUE',              'CLOB');
    add_col('APPEAL_TIMELINE', 'NEW_VALUE',              'CLOB');

    -- Reopen timestamp on complaints
    add_col('COMPLAINTS', 'REOPENED_AT',                 'TIMESTAMP(6)');
END;
