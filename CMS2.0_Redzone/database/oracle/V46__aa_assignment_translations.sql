DECLARE
    PROCEDURE add_key(p_code VARCHAR2, p_default VARCHAR2) IS
        v_exists NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_exists FROM TRANSLATION_KEYS WHERE CODE = p_code;
        IF v_exists = 0 THEN
            INSERT INTO TRANSLATION_KEYS (CODE, MODULE, DEFAULT_VALUE, CREATED_AT, UPDATED_AT)
            VALUES (p_code, 'aa-assignment', p_default, SYSTIMESTAMP, SYSTIMESTAMP);
        END IF;
    END;

    PROCEDURE add_translation(p_code VARCHAR2, p_locale VARCHAR2, p_value VARCHAR2) IS
        v_key_id NUMBER;
        v_exists NUMBER;
    BEGIN
        BEGIN
            SELECT ID INTO v_key_id FROM TRANSLATION_KEYS WHERE CODE = p_code;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RETURN;
        END;
        SELECT COUNT(*) INTO v_exists FROM TRANSLATIONS
         WHERE TRANSLATION_KEY_ID = v_key_id AND LOCALE = p_locale;
        IF v_exists = 0 THEN
            INSERT INTO TRANSLATIONS (TRANSLATION_KEY_ID, LOCALE, "VALUE", UPDATED_AT)
            VALUES (v_key_id, p_locale, p_value, SYSTIMESTAMP);
        END IF;
    END;
