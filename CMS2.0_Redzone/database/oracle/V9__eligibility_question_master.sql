-- ═══ Correct the Scheme year in already-seeded translations ═══
-- The seeders are insert-if-absent, so environments seeded before this migration still hold
-- "Integrated Ombudsman Scheme, 2026" for clauses that belong to the 2021 Scheme. Citizens are
-- shown this text verbatim when a complaint is closed as non-maintainable, so it must be corrected
-- in place rather than only in the seeder defaults.
--
-- Scoped by key code, not by the English phrase: the localized rows are in native scripts, so no
-- English substring matches them. Bengali also stores the year in Bengali numerals, which an ASCII
-- '2026' replacement would silently skip -- UNISTR is used so the literal survives any client charset.
-- VALUE / DEFAULT_VALUE are CLOB, so DBMS_LOB.SUBSTR is used to hand a VARCHAR2 to REPLACE.
UPDATE TRANSLATIONS t
   SET t.VALUE = TO_CLOB(REPLACE(REPLACE(DBMS_LOB.SUBSTR(t.VALUE, 32767, 1),
                                         '2026', '2021'),
                                 UNISTR('\09E8\09E6\09E8\09EC'), UNISTR('\09E8\09E6\09E8\09E7')))
 WHERE t.VALUE IS NOT NULL
   AND EXISTS (SELECT 1 FROM TRANSLATION_KEYS k
                WHERE k.ID = t.TRANSLATION_KEY_ID
                  AND k.CODE IN ('eligibility.block_not_filed', 'eligibility.passed_message',
                                 'home.ct_regulated'));

UPDATE TRANSLATION_KEYS k
   SET k.DEFAULT_VALUE = TO_CLOB(REPLACE(REPLACE(DBMS_LOB.SUBSTR(k.DEFAULT_VALUE, 32767, 1),
                                                 '2026', '2021'),
                                         UNISTR('\09E8\09E6\09E8\09EC'), UNISTR('\09E8\09E6\09E8\09E7')))
 WHERE k.CODE IN ('eligibility.block_not_filed', 'eligibility.passed_message', 'home.ct_regulated')
   AND k.DEFAULT_VALUE IS NOT NULL;

COMMIT;
