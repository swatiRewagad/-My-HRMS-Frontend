DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_EQM_SCHEME';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_EQM_SCHEME ON ELIGIBILITY_QUESTION_MASTER(SCHEME_VERSION)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_EQM_ENTITY_TYPE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_EQM_ENTITY_TYPE ON ELIGIBILITY_QUESTION_MASTER(APPLICABLE_ENTITY_TYPE)';
