-- Oracle version
--
-- Context: the citizen filing wizard's maintainability questions, their block rules and their
-- Scheme clause references were hardcoded in the Angular component
-- (file-complaint.component.ts eligibilityQuestions[]). A Scheme amendment therefore needed a
-- frontend release, and the hardcoded text had already drifted — it cited
-- "Integrated Ombudsman Scheme, 2026" for clauses that belong to the 2021 Scheme.
--
-- Rows are seeded by EligibilityQuestionMasterSeeder (insert-if-absent on
-- scheme_version + question_key) so operator edits made through the master survive a restart.
-- Served to the portal by GET /api/v1/eligibility/questions.
--
-- Mirrors the AUTO_CLOSURE_QUESTIONS shape (see V5__complete_ddl_dml.sql).

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES
     WHERE TABLE_NAME = 'ELIGIBILITY_QUESTION_MASTER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE ELIGIBILITY_QUESTION_MASTER (
                ID                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                SCHEME_VERSION          VARCHAR2(20) NOT NULL,
                APPLICABLE_ENTITY_TYPE  VARCHAR2(20) NOT NULL,
                QUESTION_NUMBER         NUMBER(10) NOT NULL,
                QUESTION_KEY            VARCHAR2(60) NOT NULL,
                QUESTION_TYPE           VARCHAR2(20) NOT NULL,
                QUESTION_TEXT           CLOB NOT NULL,
                TRANSLATION_KEY         VARCHAR2(120),
                BLOCK_ON                VARCHAR2(20),
                BLOCK_MESSAGE           CLOB,
                BLOCK_MESSAGE_KEY       VARCHAR2(120),
                CLAUSE_REFERENCE        VARCHAR2(100),
                NON_MAINTAINABLE        NUMBER(1) DEFAULT 0,
                SIMPLIFIED_TEXT         CLOB,
                SIMPLIFIED_TEXT_KEY     VARCHAR2(120),
                INLINE_SUB_QUESTION     NUMBER(1) DEFAULT 0,
                ACTIVE                  NUMBER(1) DEFAULT 1,
                CREATED_AT              TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
                UPDATED_AT              TIMESTAMP(6) DEFAULT SYSTIMESTAMP
            )';
    END IF;
END;
